_RE_WX = re.compile(r"\[(" + "|".join(WX_EMOJI.keys()) + r")\]")


def inbound(text):
    """[呲牙] -> 😁（给模型看）。"""
    return _RE_WX.sub(lambda m: WX_EMOJI[m.group(1)], text or "")


def outbound(text):
    """模型若输出 [呲牙] 字样，同样翻成 emoji（微信文本可渲染）。"""
    return inbound(text)
